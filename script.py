    def lookup(self, text: str) -> Optional[Dict]:
        text = text.lower().strip()
        for name, item in self._items.items():
            if name in text:
                time = item.time
                applied = []
                for mod, val in self.modifiers.items():
                    if mod in text:
                        if val >= 1.0:
                            time *= val
                        else:
                            time += val
                        applied.append(mod)
                return {
                    "item": name,
                    "time": round(time, 1),
                    "modifiers": applied,
                    "tags": item.tags
                }
        return None

