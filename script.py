# ---------------------------------------------------------------
# 3. The Coffee AI Agent — LLM actually drives every decision
# ---------------------------------------------------------------
class CoffeeAgent:
    def __init__(self, model_name: str = "google/flan-t5-base"):
        print("⏳ Loading local model (first run may take a minute)...")
        self.menu = MenuSystem()
        self.tokenizer = AutoTokenizer.from_pretrained(model_name)
        self.model = AutoModelForSeq2SeqLM.from_pretrained(model_name)
        self.model_name = model_name
        print(f"✅ Model ready → {model_name}")

    def _generate(self, prompt: str, max_tokens: int = 60) -> str:
        inputs = self.tokenizer(prompt, return_tensors="pt", truncation=True, max_length=512)
        outputs = self.model.generate(
            **inputs, max_new_tokens=max_tokens, do_sample=False, temperature=0.1
        )
        return self.tokenizer.decode(outputs[0], skip_special_tokens=True).strip()

    # ---------- Deterministic tool: only computes numbers, never decides *what* ----------
    def price_and_time(self, item_name: str, modifiers_text: str = "") -> Dict:
        """Given a known menu item name (decided by the LLM), compute exact
        time/price. This is the one place raw arithmetic happens — the model
        is not asked to do math, since small LLMs are unreliable at it."""
        item = self.menu.get(item_name.lower().strip())
        if item is None:
            return {"item": item_name, "time": 2.5, "modifiers": []}
        time = item.time
        applied = []
        text = modifiers_text.lower()
        for mod, val in self.menu.modifiers.items():
            if mod in text:
                time = time * val if val >= 1.0 else time + val
                applied.append(mod)
        return {"item": item.name, "time": round(time, 1), "modifiers": applied}

    # ---------- LLM tool 1: intent classification ----------
    def classify_intent(self, text: str) -> str:
        prompt = (
            "Classify this coffee shop customer request into exactly one category:\n"
            "- exact_menu: names one specific drink/food clearly\n"
            "- complex_order: multiple items, a quantity, or a group of people\n"
            "- preference: mentions a diet, health, or allergy constraint\n"
            "- recommendation: vague mood, feeling, or open-ended ask, no specific item named\n\n"
            f'Request: "{text}"\n'
            "Answer with only the category name."
        )
        raw = self._generate(prompt, max_tokens=8).lower()
        for label in ["exact_menu", "complex_order", "preference", "recommendation"]:
            if label.replace("_", " ") in raw or label in raw:
                return label
        return "recommendation"  # only reached if the model output was unparseable

    # ---------- LLM tool 2: extract items from a (possibly multi-item) order ----------
    def extract_items(self, text: str) -> List[Dict]:
        menu_names = ", ".join(sorted(self.menu._items.keys()))
        prompt = (
            f"Menu items available: {menu_names}\n\n"
            f'Customer said: "{text}"\n'
            "List every menu item they want, one per line, as: quantity | item name | modifiers\n"
            "If a group size is mentioned (e.g. 'for 4 people'), multiply quantities accordingly.\n"
            "Example output:\n2 | latte | oat milk, extra hot\n1 | croissant | toasted"
        )
        raw = self._generate(prompt, max_tokens=80)
        lines = [l.strip() for l in raw.split("\n") if "|" in l]
        parsed = []
        for line in lines:
            parts = [p.strip() for p in line.split("|")]
            if len(parts) >= 2:
                qty = int(parts[0]) if parts[0].isdigit() else 1
                item_name = parts[1]
                mods = parts[2] if len(parts) > 2 else ""
                parsed.append({"quantity": qty, "item": item_name, "modifiers": mods})
        return parsed

    # ---------- LLM tool 3: open-ended recommendation ----------
    def recommend_item(self, preference_text: str, candidate_items: Optional[List[str]] = None) -> str:
        names = candidate_items or list(self.menu._items.keys())
        prompt = (
            f'A customer said: "{preference_text}"\n'
            f"Menu options: {', '.join(names)}.\n"
            "Reply with ONLY the single best matching item name, nothing else."
        )
        raw = self._generate(prompt, max_tokens=12).lower().strip()
        for name in sorted(names, key=len, reverse=True):
            if name in raw:
                return name
        return names[0]  # model output didn't match anything on the menu

    # ---------- LLM tool 4: dietary/preference filtering ----------
    def filter_by_constraint(self, text: str) -> List[str]:
        all_items = list(self.menu._items.keys())
        prompt = (
            f'Customer constraint: "{text}"\n'
            f"Full menu: {', '.join(all_items)}\n"
            "List ONLY the menu items that are safe/suitable for this constraint, "
            "comma-separated, nothing else."
        )
        raw = self._generate(prompt, max_tokens=60).lower()
        matched = [name for name in all_items if name in raw]
        return matched if matched else all_items  # constraint too strict/unparsed – don't empty the menu

    # ---------- Main agent entry point ----------
    def handle(self, request: str) -> AgentResponse:
        steps = []
        intent = self.classify_intent(request)
        steps.append(f"LLM classified intent → {intent}")

        if intent == "exact_menu":
            extracted = self.extract_items(request)
            steps.append(f"LLM extracted items → {extracted}")
            if not extracted:
                extracted = [{"quantity": 1, "item": request, "modifiers": ""}]
            total, names = 0.0, []
            for e in extracted:
                result = self.price_and_time(e["item"], e["modifiers"])
                total += result["time"] * e["quantity"]
                names.append(f"{e['quantity']}x {result['item'].title()}")
                steps.append(f"Priced → {result['item']} ({result['time']} min × {e['quantity']})")
            return AgentResponse(", ".join(names), round(total, 1), "menu_lookup",
                                  "\n".join(steps), confidence=0.93)

        if intent == "complex_order":
            extracted = self.extract_items(request)
            steps.append(f"LLM extracted items → {extracted}")
            total, names = 0.0, []
            for e in extracted:
                result = self.price_and_time(e["item"], e["modifiers"])
                total += result["time"] * e["quantity"]
                names.append(f"{e['quantity']}x {result['item'].title()}")
                steps.append(f"Priced → {result['item']} ({result['time']} min × {e['quantity']})")
            if not extracted:
                steps.append("LLM extraction returned nothing usable — falling back to single-item read")
                rec = self.recommend_item(request)
                result = self.price_and_time(rec)
                names, total = [result["item"].title()], result["time"]
            return AgentResponse(", ".join(names), round(total, 1), "smart_agent",
                                  "\n".join(steps), confidence=0.87)

        if intent == "preference":
            candidates = self.filter_by_constraint(request)
            steps.append(f"LLM filtered candidates → {candidates}")
            rec = self.recommend_item(request, candidates)
            result = self.price_and_time(rec)
            steps.append(f"LLM recommended → {result['item']} ({result['time']} min)")
            return AgentResponse(result["item"].title(), result["time"], "llm_recommendation",
                                  "\n".join(steps), confidence=0.85)

        # recommendation (fully open-ended)
        rec = self.recommend_item(request)
        result = self.price_and_time(rec)
        steps.append(f"LLM recommended → {result['item']} ({result['time']} min)")
        return AgentResponse(result["item"].title(), result["time"], "llm_recommendation",
                              "\n".join(steps), confidence=0.82)

