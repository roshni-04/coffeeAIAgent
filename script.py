# ---------------------------------------------------------------
# 4. The Coffee AI Agent
# ---------------------------------------------------------------
class CoffeeAgent:
    def __init__(self, model_name: str = "google/flan-t5-base"):
        print("⏳ Loading local model (first run may take a minute)...")
        self.menu = MenuSystem()
        self.tokenizer = AutoTokenizer.from_pretrained(model_name)
        self.model = AutoModelForSeq2SeqLM.from_pretrained(model_name)
        self.model_name = model_name
        print(f"✅ Model ready → {model_name}")

    def _generate(self, prompt: str, max_tokens: int = 40) -> str:
        inputs = self.tokenizer(prompt, return_tensors="pt", truncation=True, max_length=512)
        outputs = self.model.generate(
            **inputs,
            max_new_tokens=max_tokens,
            do_sample=False,
            temperature=0.1
        )
        return self.tokenizer.decode(outputs[0], skip_special_tokens=True).strip()

    # ---------- Deterministic Tools ----------
    def menu_lookup(self, text: str) -> Optional[Dict]:
        return self.menu.lookup(text)

    def split_order(self, text: str) -> List[str]:
        text = text.lower()
        m = re.search(r'for\s+(\d+)', text)
        group = int(m.group(1)) if m else 1
        text = re.sub(r'for\s+\d+.*', '', text)
        text = re.sub(r'\b(and|plus|with|also)\b', ',', text)
        parts = [p.strip() for p in text.split(',') if p.strip()]
        expanded = []
        for p in parts:
            q = re.match(r'(\d+)\s*(.+)', p)
            if q:
                expanded.extend([q.group(2).strip()] * int(q.group(1)))
            else:
                expanded.append(p)
        return expanded * max(1, group)

    # ---------- Fixed Recommendation Logic ----------
    def recommend_item(self, preference_text: str, candidate_items: Optional[List[str]] = None) -> str:
        text = preference_text.lower()
        wanted_tags: Set[str] = set()
        for keyword, tags in _KEYWORD_TAGS.items():
            if keyword in text:
                wanted_tags.update(tags)

        items = self.menu.all_items()
        if candidate_items:
            items = [i for i in items if i.name in candidate_items] or items

        if not wanted_tags:
            # default preference
            preferred = next((i for i in items if i.name == "latte"), None)
            return preferred.name if preferred else items[0].name

        def score(item: MenuItem) -> float:
            overlap = wanted_tags.intersection(item.tags)
            if not overlap:
                return 0.0
            # Jaccard-style: penalizes items with many unrelated tags
            return len(overlap) / len(set(item.tags) | wanted_tags)

        scored = [(score(i), i) for i in items]
        best_score = max(s for s, _ in scored)
        best_items = [i for s, i in scored if s == best_score]

        # Tie-break by specificity (fewest tags = more targeted)
        best_items.sort(key=lambda i: len(i.tags))
        return best_items[0].name

    def classify_intent(self, text: str) -> str:
        lower = text.lower()
        # Fast rule-based shortcuts first
        if any(w in lower for w in ["for ", "people", "colleagues", "of us", "x ", "×"]):
            return "complex_order"
        if any(w in lower for w in ["something", "surprise", "recommend", "suggest", "what should", "tired", "sleep", "hurry", "healthy", "birthday", "lactose", "vegan"]):
            return "preference"
        # Try exact match
        if self.menu.lookup(text):
            return "exact_menu"
        return "preference"

    # ---------- Main Agent Entry ----------
    def handle(self, request: str) -> AgentResponse:
        intent = self.classify_intent(request)
        steps = [f"Intent → {intent}"]

        # ----- Exact menu -----
        if intent == "exact_menu":
            items = [i.strip() for i in re.split(r',| and ', request) if i.strip()]
            total = 0.0
            names = []
            for item in items:
                found = self.menu_lookup(item)
                if found:
                    total += found["time"]
                    names.append(found["item"].title())
                    steps.append(f"Menu lookup → {found['item']} ({found['time']} min)")
                else:
                    rec = self.recommend_item(item)
                    found = self.menu_lookup(rec) or {"item": rec, "time": 2.5}
                    total += found["time"]
                    names.append(found["item"].title())
                    steps.append(f"Fallback reco → {found['item']}")
            return AgentResponse(
                recommendation=", ".join(names),
                estimated_time_min=round(total, 1),
                method="menu_lookup",
                reasoning="\n".join(steps),
                confidence=0.95
            )

        # ----- Complex / quantity -----
        if intent == "complex_order":
            parts = self.split_order(request)
            steps.append(f"Split → {parts}")
            total = 0.0
            names = []
            for p in parts:
                found = self.menu_lookup(p)
                if found:
                    total += found["time"]
                    names.append(found["item"].title())
                    steps.append(f"Menu → {found['item']} ({found['time']} min)")
                else:
                    rec = self.recommend_item(p)
                    found = self.menu_lookup(rec) or {"item": rec, "time": 2.5}
                    total += found["time"]
                    names.append(found["item"].title())
                    steps.append(f"AI reco → {found['item']}")
            return AgentResponse(
                recommendation=", ".join(names),
                estimated_time_min=round(total, 1),
                method="smart_agent",
                reasoning="\n".join(steps),
                confidence=0.90
            )

        # ----- Preference / recommendation -----
        rec_name = self.recommend_item(request)
        found = self.menu_lookup(rec_name) or {"item": rec_name, "time": 2.5}
        steps.append(f"Scored recommendation → {found['item']}")
